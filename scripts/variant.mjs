#!/usr/bin/env node
// Add a grammar variant to grammars/index.json, either by building one from a git
// ref or by registering files you already have.
//
//   Build from a repo at a ref (a URL is cloned into .cache/, a local path is used
//   in place via a throwaway worktree, so your checkout is never touched):
//
//     node scripts/variant.mjs build --id ionide-0.3.11 --repo C:/git/tree-sitter-fsharp \
//       --ref 0.3.11 --subdir fsharp
//
//   Register files directly — a local build, a downloaded release artifact, or a
//   single edited query file:
//
//     node scripts/variant.mjs add --id my-build --label "local wip" \
//       --wasm ../my/parser.wasm --highlights ../my/queries/highlights.scm
//
//   Remove one:  node scripts/variant.mjs rm --id my-build
//   List:        node scripts/variant.mjs ls
//
// The tree-sitter CLI is taken from $TREE_SITTER, else `npx tree-sitter`. It must be
// the same major/minor as vendor/web-tree-sitter.js or the runtime will refuse the
// parser's ABI.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const GRAMMARS = path.join(ROOT, 'grammars');
const INDEX = path.join(GRAMMARS, 'index.json');
const CACHE = path.join(ROOT, '.cache', 'repos');

/* ------------------------------------------------------------------ util --- */

const die = (msg) => { console.error('error: ' + msg); process.exit(1); };

/** Manifest entries may be repo-relative paths or absolute URLs fetched at load time. */
const isUrl = (s) => typeof s === 'string' && /^https?:\/\//i.test(s);

/**
 * An id becomes a directory name under grammars/, so it must not be able to escape
 * it: `--id ..` would otherwise make `rm` delete the whole project.
 */
function checkId(id) {
  if (!id || id === true) die('--id is required');
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(id) || id === '.' || id === '..')
    die(`--id must be letters, digits, dot, dash or underscore (got "${id}")`);
  return id;
}

function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) out[a.slice(2)] = argv[i + 1]?.startsWith('--') ? true : argv[++i];
    else out._.push(a);
  }
  return out;
}

// stdio:"inherit" makes execFileSync return null rather than a string, so callers
// that only care about the exit status can pass it without blowing up here.
const run = (cmd, args, opts = {}) =>
  (execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], ...opts } ) ?? '').trim();

/**
 * Resolve the tree-sitter CLI. Prefers this project's pinned devDependency, whose
 * version is kept in step with vendor/web-tree-sitter.js: a parser generated by a
 * newer CLI than the runtime is refused at load time with an ABI error.
 * Node refuses to spawnSync a .cmd shim without a shell, hence the shell flag.
 */
function treeSitter(args, cwd) {
  const exe = process.platform === 'win32' ? 'tree-sitter.exe' : 'tree-sitter';
  const pkg = path.join(ROOT, 'node_modules', 'tree-sitter-cli');
  const local = path.join(pkg, exe);
  const cmd = process.env.TREE_SITTER || (fs.existsSync(local) ? local : null);
  if (cmd) return run(cmd, args, { cwd });
  // npm may skip a dependency's install script, leaving the package without its
  // binary. Say so instead of failing later with an opaque spawn error.
  if (fs.existsSync(pkg))
    die(`tree-sitter-cli is installed but has no ${exe}.\n` +
        `  Fetch it with:  node node_modules/tree-sitter-cli/install.js\n` +
        `  (run from ${ROOT} — it writes to the current directory)\n` +
        `  Or point at an existing CLI:  TREE_SITTER=/path/to/tree-sitter`);
  const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
  return run(npx, ['tree-sitter', ...args], { cwd, shell: process.platform === 'win32' });
}

function readIndex() {
  if (!fs.existsSync(INDEX)) return { variants: [] };
  return JSON.parse(fs.readFileSync(INDEX, 'utf8'));
}

function writeIndex(idx) {
  idx.variants.sort((a, b) => a.id.localeCompare(b.id));
  fs.writeFileSync(INDEX, JSON.stringify(idx, null, 2) + '\n');
}

function upsert(entry) {
  const idx = readIndex();
  const i = idx.variants.findIndex(v => v.id === entry.id);
  if (i >= 0) idx.variants[i] = entry; else idx.variants.push(entry);
  writeIndex(idx);
  console.log(`${i >= 0 ? 'updated' : 'added'} variant "${entry.id}"`);
}

/** Copy a file in, returning its path relative to grammars/ for the manifest. */
function place(id, src, name) {
  const destDir = path.join(GRAMMARS, id);
  fs.mkdirSync(destDir, { recursive: true });
  fs.copyFileSync(src, path.join(destDir, name));
  return `${id}/${name}`;
}

/* ----------------------------------------------------------------- build --- */

function ensureClone(repo) {
  if (fs.existsSync(path.join(repo, '.git')) || fs.existsSync(path.join(repo, 'HEAD')))
    return path.resolve(repo);                       // already a local checkout
  const name = repo.replace(/[/\\:]+/g, '_').replace(/^_+|_+$/g, '');
  const dest = path.join(CACHE, name);
  if (!fs.existsSync(dest)) {
    fs.mkdirSync(CACHE, { recursive: true });
    console.log(`cloning ${repo} …`);
    run('git', ['clone', '--quiet', repo, dest], { stdio: 'inherit' });
  } else {
    run('git', ['-C', dest, 'fetch', '--quiet', '--tags', '--force'], { stdio: 'inherit' });
  }
  return dest;
}

function cmdBuild(a) {
  checkId(a.id);
  if (!a.repo) die('--repo is required (a git URL or a local checkout path)');

  const repo = ensureClone(a.repo);
  const ref = a.ref || run('git', ['-C', repo, 'rev-parse', '--abbrev-ref', 'HEAD']);
  let sha;
  try { sha = run('git', ['-C', repo, 'rev-parse', '--short', ref]); }
  catch { die(`ref "${ref}" not found in ${repo}`); }

  // A detached worktree, so a dirty or differently-checked-out repo is safe to use.
  const wt = fs.mkdtempSync(path.join(os.tmpdir(), 'ts-variant-'));
  fs.rmSync(wt, { recursive: true, force: true });
  console.log(`checking out ${ref} (${sha}) …`);
  run('git', ['-C', repo, 'worktree', 'add', '--detach', '--quiet', wt, sha], { stdio: 'inherit' });

  try {
    const destDir = path.join(GRAMMARS, a.id);
    fs.mkdirSync(destDir, { recursive: true });
    const wasm = path.join(destDir, 'parser.wasm');

    const buildArgs = ['build', '--wasm', '-o', wasm];
    if (a.subdir && a.subdir !== true) buildArgs.push(a.subdir);
    console.log('building wasm (this takes a minute the first time) …');
    treeSitter(buildArgs, wt);

    // Queries live next to the grammar for a subdir layout, else at the repo root.
    const qDirs = [
      a.queries && a.queries !== true ? a.queries : null,
      a.subdir && a.subdir !== true ? path.join(a.subdir, 'queries') : null,
      'queries',
    ].filter(Boolean);

    const entry = {
      id: a.id,
      label: a.label && a.label !== true ? a.label : a.id,
      version: a.version && a.version !== true ? a.version : `${ref} @ ${sha}`,
      repo: /^https?:|^git@/.test(a.repo) ? a.repo : undefined,
      wasm: `${a.id}/parser.wasm`,
    };
    for (const q of ['highlights', 'tags']) {
      const found = qDirs.map(d => path.join(wt, d, `${q}.scm`)).find(p => fs.existsSync(p));
      if (found) entry[q] = place(a.id, found, `${q}.scm`);
      else console.warn(`  note: no ${q}.scm found in ${qDirs.join(', ')}`);
    }
    upsert(entry);
  } finally {
    run('git', ['-C', repo, 'worktree', 'remove', '--force', wt], { stdio: 'inherit' });
  }
}

/* ------------------------------------------------------------------- add --- */

function cmdAdd(a) {
  checkId(a.id);
  const existing = readIndex().variants.find(v => v.id === a.id) || {};
  const entry = {
    ...existing,
    id: a.id,
    label: a.label && a.label !== true ? a.label : (existing.label || a.id),
    version: a.version && a.version !== true ? a.version : (existing.version || 'local'),
  };
  let touched = false;
  for (const [flag, name, key] of [
    ['wasm', 'parser.wasm', 'wasm'],
    ['highlights', 'highlights.scm', 'highlights'],
    ['tags', 'tags.scm', 'tags'],
  ]) {
    const src = a[flag];
    if (!src || src === true) continue;
    if (!fs.existsSync(src)) die(`${flag}: no such file: ${src}`);
    entry[key] = place(a.id, src, name);
    touched = true;
  }
  if (!touched && !existing.wasm) die('give at least --wasm (or --highlights / --tags)');
  if (!entry.wasm) die(`variant "${a.id}" has no wasm; pass --wasm`);
  upsert(entry);
}

/* -------------------------------------------------------------- rm / ls --- */

function cmdRm(a) {
  checkId(a.id);
  const idx = readIndex();
  const before = idx.variants.length;
  idx.variants = idx.variants.filter(v => v.id !== a.id);
  if (idx.variants.length === before) die(`no variant "${a.id}"`);
  writeIndex(idx);
  fs.rmSync(path.join(GRAMMARS, a.id), { recursive: true, force: true });
  console.log(`removed variant "${a.id}"`);
}

function cmdLs() {
  for (const v of readIndex().variants) {
    const size = isUrl(v.wasm) ? 'remote'
      : fs.existsSync(path.join(GRAMMARS, v.wasm))
        ? (fs.statSync(path.join(GRAMMARS, v.wasm)).size / 1048576).toFixed(1) + ' MB'
        : 'MISSING';
    console.log(`${v.id.padEnd(22)} ${String(v.version).padEnd(24)} ${size.padStart(8)}  ${v.label}`);
  }
}

/* ------------------------------------------------------------------ main --- */

const a = parseArgs(process.argv.slice(2));
const cmd = a._[0];
if (cmd === 'build') cmdBuild(a);
else if (cmd === 'add') cmdAdd(a);
else if (cmd === 'rm') cmdRm(a);
else if (cmd === 'ls') cmdLs();
else {
  console.log(fs.readFileSync(import.meta.filename, 'utf8')
    .split('\n').slice(1).filter(l => l.startsWith('//')).map(l => l.slice(3)).join('\n'));
  process.exit(cmd ? 1 : 0);
}
